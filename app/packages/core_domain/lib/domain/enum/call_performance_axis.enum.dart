/// Commercial competencies displayed in the post-call radar.
enum CallPerformanceAxis {
  /// Quality of active listening and response to prospect cues.
  listening,

  /// Quality of needs discovery and useful questioning.
  discovery,

  /// Simplicity and structure of the seller's message.
  clarity,

  /// Verbal assurance without unnecessary hedging.
  confidence,

  /// Ability to connect the offer to a concrete customer outcome.
  value,

  /// Degree to which the conversation is adapted to this prospect.
  personalization,

  /// Ability to move the conversation toward an explicit next step.
  progression,

  /// Human, conversational delivery rather than scripted pressure.
  naturalness,
}
