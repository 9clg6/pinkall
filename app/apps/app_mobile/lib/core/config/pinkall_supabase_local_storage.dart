import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:supabase_flutter/supabase_flutter.dart';

/// Minimal secure key/value boundary used to keep session migration testable.
abstract interface class PinkallSecureKeyValueStore {
  /// Reads the value stored under [key], if any.
  Future<String?> read(String key);

  /// Encrypts and stores [value] under [key].
  Future<void> write(String key, String value);

  /// Deletes the value stored under [key].
  Future<void> delete(String key);
}

/// Minimal legacy store boundary for the previous SharedPreferences session.
abstract interface class PinkallLegacySessionStore {
  /// Reads the former plaintext session stored under [key].
  Future<String?> read(String key);

  /// Deletes the former plaintext session stored under [key].
  Future<void> remove(String key);
}

/// Keychain/Keystore implementation used on iOS, Android and macOS.
final class FlutterPinkallSecureKeyValueStore
    implements PinkallSecureKeyValueStore {
  /// Creates the production Keychain/Keystore adapter.
  const FlutterPinkallSecureKeyValueStore({
    FlutterSecureStorage storage = const FlutterSecureStorage(
      aOptions: AndroidOptions(
        migrateWithBackup: true,
        storageNamespace: 'pinkall_supabase_auth',
      ),
      iOptions: IOSOptions(
        accountName: 'com.pinkall.supabase.auth',
        accessibility: KeychainAccessibility.first_unlock_this_device,
      ),
      mOptions: MacOsOptions(
        accountName: 'com.pinkall.supabase.auth',
        accessibility: KeychainAccessibility.first_unlock_this_device,
        // The POC is ad-hoc signed. The login Keychain remains encrypted and
        // avoids the development-certificate entitlement required by macOS's
        // data-protection Keychain.
        usesDataProtectionKeychain: false,
      ),
    ),
  }) : _storage = storage;

  final FlutterSecureStorage _storage;

  @override
  Future<void> delete(String key) => _storage.delete(key: key);

  @override
  Future<String?> read(String key) => _storage.read(key: key);

  @override
  Future<void> write(String key, String value) =>
      _storage.write(key: key, value: value);
}

/// Reads and removes sessions created by Supabase's former default storage.
final class SharedPreferencesPinkallLegacySessionStore
    implements PinkallLegacySessionStore {
  SharedPreferences? _preferences;

  Future<SharedPreferences> _instance() async =>
      _preferences ??= await SharedPreferences.getInstance();

  @override
  Future<String?> read(String key) async => (await _instance()).getString(key);

  @override
  Future<void> remove(String key) async {
    await (await _instance()).remove(key);
  }
}

/// Supabase auth storage backed by the OS Keychain/Keystore.
///
/// On first use, an existing plaintext SharedPreferences session is copied,
/// verified in secure storage, then removed from the legacy store. No session
/// payload is retained in fields or included in errors/toString output.
final class PinkallSecureSupabaseLocalStorage extends LocalStorage {
  /// Creates secure storage for the Supabase project at [projectUrl].
  PinkallSecureSupabaseLocalStorage({
    required Uri projectUrl,
    PinkallSecureKeyValueStore secureStore =
        const FlutterPinkallSecureKeyValueStore(),
    PinkallLegacySessionStore? legacyStore,
  }) : _sessionKey = sessionKeyFor(projectUrl),
       _secureStore = secureStore,
       _legacyStore =
           legacyStore ?? SharedPreferencesPinkallLegacySessionStore();

  final String _sessionKey;
  final PinkallSecureKeyValueStore _secureStore;
  final PinkallLegacySessionStore _legacyStore;
  Future<void>? _initialization;

  /// Matches the key generated by supabase_flutter for its default storage.
  static String sessionKeyFor(Uri projectUrl) =>
      'sb-${projectUrl.host.split('.').first}-auth-token';

  @override
  Future<void> initialize() => _initialization ??= _migrateLegacySession();

  Future<void> _migrateLegacySession() async {
    final String? secureSession = await _secureStore.read(_sessionKey);
    final String? legacySession = await _legacyStore.read(_sessionKey);

    if (secureSession != null && secureSession.isNotEmpty) {
      if (legacySession != null) {
        await _legacyStore.remove(_sessionKey);
      }
      return;
    }

    if (secureSession != null) {
      await _secureStore.delete(_sessionKey);
    }
    if (legacySession == null || legacySession.isEmpty) {
      if (legacySession != null) {
        await _legacyStore.remove(_sessionKey);
      }
      return;
    }

    await _writeAndVerify(legacySession);
    await _legacyStore.remove(_sessionKey);
  }

  Future<void> _writeAndVerify(String session) async {
    await _secureStore.write(_sessionKey, session);
    if (await _secureStore.read(_sessionKey) != session) {
      await _secureStore.delete(_sessionKey);
      throw StateError('La session Supabase n’a pas pu être sécurisée.');
    }
  }

  @override
  Future<bool> hasAccessToken() async {
    final String? session = await accessToken();
    return session != null && session.isNotEmpty;
  }

  @override
  Future<String?> accessToken() async {
    await initialize();
    final String? session = await _secureStore.read(_sessionKey);
    return session == null || session.isEmpty ? null : session;
  }

  @override
  Future<void> persistSession(String persistSessionString) async {
    await initialize();
    if (persistSessionString.isEmpty) {
      await removePersistedSession();
      return;
    }
    await _writeAndVerify(persistSessionString);
    await _legacyStore.remove(_sessionKey);
  }

  @override
  Future<void> removePersistedSession() async {
    await initialize();
    try {
      await _secureStore.delete(_sessionKey);
    } finally {
      await _legacyStore.remove(_sessionKey);
    }
  }

  @override
  String toString() => 'PinkallSecureSupabaseLocalStorage(<redacted>)';
}
